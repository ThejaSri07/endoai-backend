// src/pages/Results.jsx
import { useEffect, useState } from "react";
import Sidebar from "../components/Sidebar";
import Navbar  from "../components/Navbar";
import MobileNav from "../components/MobileNav";
import { useNavigate } from "react-router-dom";
import { useToast } from "../components/Toast";
import jsPDF from "jspdf";

const RISK_CONFIG = {
  Low:      { color: "var(--success)", bg: "var(--success-bg)", icon: "✓" },
  Moderate: { color: "var(--warning)", bg: "var(--warning-bg)", icon: "⚠" },
  High:     { color: "var(--danger)",  bg: "var(--danger-bg)",  icon: "✕" },
};

function Results() {
  const navigate = useNavigate();
  const toast    = useToast();
  const [data, setData] = useState(null);

  useEffect(() => {
    const raw = localStorage.getItem("endoai_last_result");
    if (raw) {
      try {
        setData(JSON.parse(raw));
      } catch (e) {
        console.error("Result parse error", e);
      }
    }
  }, []);

  const handleExportPDF = () => {
    if (!data) return;
    const doc  = new jsPDF();
    const r    = data.result || data;
    const risk = r.risk || "—";

    doc.setFillColor(10, 61, 98);
    doc.rect(0, 0, 210, 40, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(22); doc.setFont("helvetica", "bold");
    doc.text("EndoAI", 14, 18);
    doc.setFontSize(10); doc.setFont("helvetica", "normal");
    doc.text("AI-Based Volumetric Canal Planning Report", 14, 27);
    doc.text(`Generated: ${new Date().toLocaleDateString()}`, 14, 34);

    doc.setTextColor(0, 0, 0);
    doc.setFontSize(14); doc.setFont("helvetica", "bold");
    doc.text("Case Information", 14, 52);
    doc.setFontSize(10);
    [
      ["Case ID",      data.caseId    || data.case_id],
      ["Patient ID",   data.patientId || data.patient_id],
      ["Tooth Number", `#${data.tooth}`],
      ["Analysis Date", data.uploadDate || data.upload_date],
      ["Canals Found", `${r.n_canals} canal${r.n_canals > 1 ? "s" : ""}`],
      ["Risk Level",   risk],
    ].forEach(([k, v], i) => {
      doc.setFont("helvetica", "bold");   doc.text(`${k}:`, 14, 62 + i * 8);
      doc.setFont("helvetica", "normal"); doc.text(String(v || "—"), 65, 62 + i * 8);
    });

    doc.setFontSize(14); doc.setFont("helvetica", "bold");
    doc.text("Volumetric Measurements", 14, 118);
    doc.setFontSize(10);
    [
      ["Canal Volume",     `${r.canal_volume} mm³`],
      ["Canal Length",     `${r.canal_length} mm`],
      ["Curvature",        `${r.curvature}°`],
      ["Dentin Thickness", `${r.dentin} mm`],
    ].forEach(([k, v], i) => {
      doc.setFont("helvetica", "bold");   doc.text(`${k}:`, 14, 128 + i * 8);
      doc.setFont("helvetica", "normal"); doc.text(v, 70, 128 + i * 8);
    });

    doc.setFontSize(14); doc.setFont("helvetica", "bold");
    doc.text("Risk Assessment", 14, 168);
    doc.setFontSize(10);
    [
      ["Canal Calcification",   `${r.calcification}%`],
      ["Ledge Formation Risk",  `${r.ledge_risk}%`],
      ["Perforation Risk",      `${r.perf_risk}%`],
      ["Instrument Separation", `${r.sep_risk}%`],
    ].forEach(([k, v], i) => {
      doc.setFont("helvetica", "bold");   doc.text(`${k}:`, 14, 178 + i * 8);
      doc.setFont("helvetica", "normal"); doc.text(v, 80, 178 + i * 8);
    });

    doc.setFontSize(14); doc.setFont("helvetica", "bold");
    doc.text("Treatment Recommendation", 14, 218);
    doc.setFontSize(10);
    [
      ["Suggested Taper", r.taper],
      ["Apical Size",     r.apical],
      ["Irrigation",      r.irrigation],
      ["Obturation",      r.obturation],
    ].forEach(([k, v], i) => {
      doc.setFont("helvetica", "bold");   doc.text(`${k}:`, 14, 228 + i * 8);
      doc.setFont("helvetica", "normal"); doc.text(v || "—", 70, 228 + i * 8);
    });

    doc.setFillColor(244, 247, 251);
    doc.rect(0, 272, 210, 25, "F");
    doc.setTextColor(100, 100, 100); doc.setFontSize(8);
    doc.text("This report is generated by EndoAI and is intended for clinical reference only.", 14, 280);
    doc.text("© 2026 EndoAI · HIPAA Compliant", 14, 286);

    doc.save(`EndoAI_${data.caseId || data.case_id}.pdf`);
    toast("PDF exported successfully!", "success");
  };

  if (!data) {
    return (
      <div className="app-layout">
        <Sidebar />
        <div className="main-content">
          <Navbar />
          <div className="content-container" style={{ display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center", minHeight: "60vh", color: "var(--text-muted)", textAlign: "center" }}>
            <svg width="48" height="48" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="1.5" style={{ marginBottom: "16px", opacity: 0.4 }}>
              <polyline points="22 12 18 12 15 21 9 3 6 12 2 12"/>
            </svg>
            <h2 style={{ marginBottom: "6px" }}>No Analysis Yet</h2>
            <p style={{ marginBottom: "20px", fontSize: "14px" }}>Upload a CBCT scan to view the segmented canal metrics.</p>
            <button onClick={() => navigate("/upload")} className="btn btn-primary">
              Go to Upload
            </button>
          </div>
        </div>
        <MobileNav />
      </div>
    );
  }

  const r    = data.result || data;
  const risk = RISK_CONFIG[r.risk] || RISK_CONFIG.Moderate;

  const infoRows = [
    ["Case ID",      data.caseId    || data.case_id],
    ["Patient ID",   data.patientId || data.patient_id],
    ["Tooth Number", `#${data.tooth}`],
    ["Analysis Date", data.uploadDate || data.upload_date],
    ["Canals Found", `${r.n_canals} canal${r.n_canals > 1 ? "s" : ""}`],
    ["Source",       r.source === "ai_model" ? "AI Model (ToothFairy3)" : "Anatomy Rules Engine"],
  ];

  const metrics = [
    { label: "Canal Volume",     value: r.canal_volume,    unit: "mm³", accent: "var(--info)" },
    { label: "Canal Length",     value: r.canal_length,    unit: "mm",  accent: "var(--success)" },
    { label: "Curvature",        value: `${r.curvature}°`, unit: "",    accent: "var(--warning)" },
    { label: "Dentin Thickness", value: r.dentin,          unit: "mm",  accent: "var(--primary-light)" },
  ];

  const riskBars = [
    { label: "Canal Calcification",   pct: r.calcification, color: "var(--warning)" },
    { label: "Ledge Formation Risk",  pct: r.ledge_risk,    color: "var(--warning)" },
    { label: "Perforation Risk",      pct: r.perf_risk,     color: "var(--success)" },
    { label: "Instrument Separation", pct: r.sep_risk,      color: "var(--info)" },
  ];

  const recos = [
    ["Suggested Taper", r.taper],
    ["Apical Size",     r.apical],
    ["Irrigation",      r.irrigation],
    ["Obturation",      r.obturation],
  ];

  return (
    <div className="app-layout">
      <Sidebar />
      <div className="main-content">
        <Navbar />
        <div className="content-container">

          {/* Top bar */}
          <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", marginBottom: "20px", flexWrap: "wrap", gap: "12px" }}>
            <div style={{ display: "flex", alignItems: "center", gap: "8px", flexWrap: "wrap" }}>
              <div style={{ width: "9px", height: "9px", borderRadius: "50%", background: "var(--success)" }} />
              <span style={{ fontSize: "14px", color: "var(--success)", fontWeight: "700" }}>Analysis Complete</span>
              <span style={{ fontSize: "12.5px", color: "var(--text-muted)" }}>· {data.uploadDate || data.upload_date}</span>
            </div>
            <div style={{ display: "flex", gap: "8px", flexWrap: "wrap" }}>
              <button onClick={handleExportPDF}
                className="btn"
                style={{ background: "var(--surface-card)", color: "var(--text-secondary)", border: "1.5px solid var(--border-strong)", fontSize: "13px", padding: "8px 16px" }}>
                <svg width="14" height="14" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2"><path d="M21 15v4a2 2 0 01-2 2H5a2 2 0 01-2-2v-4M7 10l5 5 5-5M12 15V3"/></svg>
                Export PDF
              </button>
              <button onClick={() => navigate("/upload")}
                className="btn btn-primary"
                style={{ fontSize: "13px", padding: "8px 16px" }}>
                + New Case
              </button>
            </div>
          </div>

          <div className="two-col-layout">
            {/* LEFT */}
            <div>
              {/* 3D Viz */}
              <div style={{ background: "linear-gradient(135deg, #0A3D62 0%, #1565A8 100%)", height: "200px", borderRadius: "var(--radius-lg)", display: "flex", alignItems: "center", justifyContent: "center", flexDirection: "column", gap: "10px", marginBottom: "16px", position: "relative", overflow: "hidden" }}>
                <svg width="64" height="64" viewBox="0 0 80 80" fill="none" style={{ opacity: 0.45 }}>
                  <ellipse cx="40" cy="40" rx="30" ry="36" stroke="#90E0EF" strokeWidth="1.5"/>
                  <ellipse cx="40" cy="40" rx="20" ry="26" stroke="#90E0EF" strokeWidth="1.5"/>
                  <ellipse cx="40" cy="40" rx="10" ry="16" stroke="#90E0EF" strokeWidth="1.5"/>
                  <line x1="40" y1="4" x2="40" y2="76" stroke="#90E0EF" strokeWidth="1"/>
                  <line x1="10" y1="40" x2="70" y2="40" stroke="#90E0EF" strokeWidth="1"/>
                </svg>
                <span style={{ color: "rgba(255,255,255,0.75)", fontSize: "12.5px" }}>
                  3D Canal Volume · Tooth #{data.tooth} · {r.n_canals} canal{r.n_canals > 1 ? "s" : ""}
                </span>
                <div style={{ position: "absolute", top: "10px", right: "10px", background: "rgba(0,180,216,0.2)", border: "1px solid rgba(0,180,216,0.4)", color: "#90E0EF", padding: "2px 8px", borderRadius: "20px", fontSize: "10.5px", fontWeight: "600" }}>
                  CBCT Reconstructed
                </div>
              </div>

              {/* Case Info */}
              <div className="card" style={{ marginBottom: "16px" }}>
                <div style={{ fontSize: "11px", fontWeight: "700", color: "var(--text-muted)", textTransform: "uppercase", letterSpacing: "0.6px", marginBottom: "12px" }}>
                  Case Information
                </div>
                {infoRows.map(([k, v], i) => (
                  <div key={k} style={{ display: "flex", justifyContent: "space-between", alignItems: "center", padding: "8px 0", borderBottom: i === infoRows.length - 1 ? "none" : "1px solid var(--border)" }}>
                    <span style={{ fontSize: "12.5px", color: "var(--text-muted)" }}>{k}</span>
                    <span style={{ fontSize: "13px", fontWeight: "600", fontFamily: "var(--font-mono)" }}>{v}</span>
                  </div>
                ))}
              </div>
            </div>

            {/* RIGHT */}
            <div>
              {/* Metrics */}
              <div className="card" style={{ marginBottom: "16px" }}>
                <div style={{ fontSize: "11px", fontWeight: "700", color: "var(--text-muted)", textTransform: "uppercase", letterSpacing: "0.6px", marginBottom: "12px" }}>
                  Volumetric Measurements
                </div>
                <div className="responsive-grid">
                  {metrics.map(m => (
                    <div key={m.label} style={{ background: "var(--surface)", border: "1px solid var(--border)", borderLeft: `3px solid ${m.accent}`, borderRadius: "var(--radius)", padding: "12px 14px" }}>
                      <div style={{ fontSize: "11.5px", color: "var(--text-muted)", marginBottom: "3px" }}>{m.label}</div>
                      <div>
                        <span style={{ fontSize: "20px", fontWeight: "700", fontFamily: "var(--font-mono)" }}>{m.value}</span>
                        {m.unit && <span style={{ fontSize: "11.5px", color: "var(--text-muted)", marginLeft: "4px" }}>{m.unit}</span>}
                      </div>
                    </div>
                  ))}
                </div>
              </div>

              {/* Risk */}
              <div className="card" style={{ marginBottom: "16px" }}>
                <div style={{ fontSize: "11px", fontWeight: "700", color: "var(--text-muted)", textTransform: "uppercase", letterSpacing: "0.6px", marginBottom: "12px" }}>
                  Risk Assessment
                </div>
                <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", marginBottom: "14px" }}>
                  <span style={{ fontSize: "13px", fontWeight: "500" }}>Overall Risk Level</span>
                  <span style={{ padding: "4px 12px", borderRadius: "20px", background: risk.bg, color: risk.color, fontSize: "12px", fontWeight: "700" }}>
                    {risk.icon} {r.risk} Risk
                  </span>
                </div>
                {riskBars.map(rb => (
                  <div key={rb.label} style={{ marginBottom: "10px" }}>
                    <div style={{ display: "flex", justifyContent: "space-between", marginBottom: "4px" }}>
                      <span style={{ fontSize: "11.5px", color: "var(--text-secondary)" }}>{rb.label}</span>
                      <span style={{ fontSize: "11.5px", fontWeight: "600", color: rb.color, fontFamily: "var(--font-mono)" }}>{rb.pct}%</span>
                    </div>
                    <div style={{ height: "5px", background: "var(--border)", borderRadius: "10px", overflow: "hidden" }}>
                      <div style={{ width: `${Math.min(rb.pct, 100)}%`, height: "100%", background: rb.color, borderRadius: "10px" }} />
                    </div>
                  </div>
                ))}
              </div>

              {/* Recommendation */}
              <div className="card">
                <div style={{ fontSize: "11px", fontWeight: "700", color: "var(--text-muted)", textTransform: "uppercase", letterSpacing: "0.6px", marginBottom: "12px" }}>
                  Preparation Recommendation
                </div>
                <div style={{ background: "var(--info-bg)", border: "1px solid rgba(37,99,235,0.18)", borderRadius: "var(--radius)", padding: "14px 16px" }}>
                  <div className="responsive-grid" style={{ gap: "10px" }}>
                    {recos.map(([k, v]) => (
                      <div key={k}>
                        <div style={{ fontSize: "11px", color: "var(--info)", fontWeight: "500", marginBottom: "2px" }}>{k}</div>
                        <div style={{ fontSize: "14px", fontWeight: "700", fontFamily: "var(--font-mono)" }}>{v}</div>
                      </div>
                    ))}
                  </div>
                </div>
                {data.notes && (
                  <div style={{ marginTop: "12px", padding: "10px 12px", background: "var(--surface)", borderRadius: "var(--radius-sm)", fontSize: "12.5px", color: "var(--text-secondary)" }}>
                    <strong style={{ color: "var(--text-primary)" }}>Clinical Notes:</strong> {data.notes}
                  </div>
                )}
              </div>
            </div>
          </div>
        </div>
      </div>
      <MobileNav />
    </div>
  );
}

export default Results;
